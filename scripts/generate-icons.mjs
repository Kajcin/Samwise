#!/usr/bin/env node
// Generates src/app/core/icons/icons.generated.ts from Bootstrap Icons (MIT,
// https://icons.getbootstrap.com), with only the icons listed below, so the app
// bundles a few KB of path data instead of the whole set or its icon font.
//
// To add an icon: find its name on icons.getbootstrap.com, add it here, and run
//   npm run icons
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const ICONS = [
  // navigation
  'house', 'list-check', 'grid-3x3', 'flower2', 'gear', 'box-arrow-right',
  // task types (see TASK_TYPE_ICONS in plant-catalog/labels.ts)
  'flower1', 'bucket', 'scissors', 'droplet', 'basket', 'grid-1x2', 'layers', 'snow', 'arrows-collapse-vertical', 'flower3',
  // actions
  'check-lg', 'arrow-counterclockwise', 'plus-lg', 'trash', 'copy', 'google',
  'calendar-plus', 'calendar-x', 'calendar-check', 'arrow-repeat', 'pencil', 'box-arrow-up-right', 'x-circle', 'search', 'upload', 'link-45deg', 'star-fill',
  // status and plant facts
  'exclamation-triangle', 'sun', 'sun-fill', 'cloud-sun', 'cloud', 'funnel', 'x-lg',
];

const out = 'src/app/core/icons/icons.generated.ts';
const version = JSON.parse(readFileSync('node_modules/bootstrap-icons/package.json', 'utf8')).version;

const entries = ICONS.map((name) => {
  const svg = readFileSync(`node_modules/bootstrap-icons/icons/${name}.svg`, 'utf8');
  if (!svg.includes('viewBox="0 0 16 16"')) throw new Error(`${name}: unexpected viewBox`);
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
  // Only <path d="…" [fill-rule="…"]/> is supported, so the component can render
  // the icons as elements instead of injecting raw SVG markup.
  const paths = [...inner.matchAll(/<(\w+)([^>]*)\/>/g)].map(([, tag, attrs]) => {
    if (tag !== 'path') throw new Error(`${name}: <${tag}> isn't supported, only <path>`);
    const d = attrs.match(/\sd="([^"]+)"/)?.[1];
    const fillRule = attrs.match(/\sfill-rule="([^"]+)"/)?.[1];
    if (!d) throw new Error(`${name}: path without d`);
    return fillRule ? { d, fillRule } : { d };
  });
  if (inner.replace(/<path[^>]*\/>/g, '').trim()) throw new Error(`${name}: unexpected markup`);
  return `  '${name}': ${JSON.stringify(paths)},`;
});

// Line icons (24 × 24, stroke 2): every .svg in scripts/icons/line (see its README).
const lineDir = 'scripts/icons/line';
const lineNames = readdirSync(lineDir).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4)).sort();
const lineEntries = lineNames.map((name) => {
  if (ICONS.includes(name)) throw new Error(`${name}: both a Bootstrap and a line icon`);
  const svg = readFileSync(`${lineDir}/${name}.svg`, 'utf8');
  if (!svg.includes('viewBox="0 0 24 24"')) throw new Error(`${name}: unexpected viewBox`);
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  const shapes = [...inner.matchAll(/<(\w+)([^>]*?)\s*\/>/g)];
  const paths = shapes.flatMap(([, tag, attrs]) => {
    const attr = (key) => attrs.match(new RegExp(`\\s${key}="([^"]+)"`))?.[1];
    if (tag === 'path') {
      // Tabler's invisible 24 × 24 bounding box.
      if (attr('stroke') === 'none') return [];
      const d = attr('d');
      if (!d) throw new Error(`${name}: path without d`);
      return [d];
    }
    if (tag === 'ellipse') return [ellipsePath(name, attrs, attr)];
    throw new Error(`${name}: <${tag}> isn't supported, only <path> and <ellipse>`);
  });
  const rest = inner.replace(/<!--[\s\S]*?-->/g, '').replace(/<(\w+)[^>]*?\/>/g, '').trim();
  if (rest) throw new Error(`${name}: unexpected markup: ${rest.slice(0, 60)}`);
  return `  '${name}': ${JSON.stringify(paths)},`;
});

/** An <ellipse>, optionally rotate(angle cx cy)'d, as a path of two arcs. */
function ellipsePath(name, attrs, attr) {
  const [cx, cy, rx, ry] = ['cx', 'cy', 'rx', 'ry'].map((key) => Number(attr(key)));
  if ([cx, cy, rx, ry].some(Number.isNaN)) throw new Error(`${name}: incomplete ellipse`);
  const rotate = attrs.match(/transform="rotate\(([-\d.]+)(?:[ ,]+[-\d.]+[ ,]+[-\d.]+)?\)"/);
  const angle = rotate ? Number(rotate[1]) : 0;
  const round = (n) => Math.round(n * 1000) / 1000;
  const dx = round(rx * Math.cos((angle * Math.PI) / 180));
  const dy = round(rx * Math.sin((angle * Math.PI) / 180));
  return `M${round(cx - dx)} ${round(cy - dy)}a${rx} ${ry} ${angle} 1 0 ${round(2 * dx)} ${round(2 * dy)}a${rx} ${ry} ${angle} 1 0 ${round(-2 * dx)} ${round(-2 * dy)}z`;
}

writeFileSync(
  out,
  `// Generated by scripts/generate-icons.mjs from bootstrap-icons@${version} (MIT). Do not edit.
// Add icons in that script and run \`npm run icons\`.

export interface IconPath {
  d: string;
  fillRule?: string;
}

export const ICONS = {
${entries.join('\n')}
} as const satisfies Record<string, readonly IconPath[]>;

/** Line icons, 24 × 24, drawn with a stroke (scripts/icons/line: Tabler Icons, MIT, and our own). */
export const LINE_ICONS = {
${lineEntries.join('\n')}
} as const satisfies Record<string, readonly string[]>;

export type IconName = keyof typeof ICONS | keyof typeof LINE_ICONS;
`,
);
console.log(`Wrote ${ICONS.length} Bootstrap and ${lineNames.length} line icons to ${out}`);
